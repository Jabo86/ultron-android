const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..", "UNVORLauncher", "app", "src", "main");
const java = fs.readFileSync(path.join(root, "java/com/ultron/launcher/MainActivity.java"), "utf8");
const js = fs.readFileSync(path.join(root, "assets/hud/home.js"), "utf8");

assert.match(java, /private final ExecutorService appsIo = Executors\.newSingleThreadExecutor\(\)/);
assert.match(java, /private final ExecutorService launchIo = Executors\.newSingleThreadExecutor\(\)/);
assert.match(java, /private volatile Set<String> knownLaunchTargets/);
assert.match(java, /private volatile JSONArray cachedApps/);
assert.match(java, /JSONArray cached=cachedApps;[\s\S]*?emit\("apps",cached\);return/);
assert.match(java, /knownLaunchTargets=Collections\.unmodifiableSet\(targets\);\s*cachedApps=quickRows/);
assert.match(java, /emit\("apps",quickRows\);[\s\S]*?cachedApps=iconRows;[\s\S]*?emit\("apps",iconRows\)/);
const fast = java.indexOf("if(knownLaunchTargets.contains(launchTarget(pkg,activity)))");
const slow = java.indexOf("launchIo.execute", fast);
assert.ok(fast > 0 && slow > fast, "The cached instant path must be reached before fallback discovery");
assert.ok(java.slice(fast, slow).includes("launchVerified("), "The cached target must immediately launch");
assert.ok(!java.slice(fast, slow).includes("launchable()"), "The cached target must not enumerate packages");
assert.match(java, /appsIo\.shutdownNow\(\);launchIo\.shutdownNow\(\)/);
assert.match(js, /const previousQuery=oldSearch\?\.value\|\|''/);
assert.match(js, /search\.value=previousQuery/);
assert.match(js, /if\(focused\)search\.focus\(\)/);
const index=fs.readFileSync(path.join(root,"assets/hud/index.html"),"utf8");
const ai=fs.readFileSync(path.join(root,"java/com/ultron/launcher/PersonalAi.java"),"utf8");
const manifest=fs.readFileSync(path.join(root,"AndroidManifest.xml"),"utf8");
assert.match(index,/id="globe-voice-button" data-action="aiOpen"/);
assert.match(js,/function openUnvorSettings\(\)/);
assert.match(js,/function aiSettings\(\)/);
assert.match(js,/function openAssistant\(\)/);
assert.match(js,/function renderAiSettings\(\)/);
for(const action of ["aiList","aiEdit","aiDelete","aiTest","aiAsk"])
  assert.ok(java.includes('case "'+action+'":'),"Missing native AI action "+action);
assert.match(ai,/KeyStore\.getInstance\("AndroidKeyStore"\)/);
assert.match(ai,/AES\/GCM\/NoPadding/);
assert.match(ai,/private final ExecutorService network/);
assert.match(ai,/for\(int priority=1;priority<=3;priority\+\+\)/);
assert.match(ai,/conn\.setInstanceFollowRedirects\(false\)/);
assert.match(ai,/safeHttps\(String raw\)/);
assert.doesNotMatch(js,/API_KEY|sk-[A-Za-z0-9]{12}|gsk_[a-zA-Z0-9]{16}/);
assert.match(manifest,/android\.permission\.INTERNET/);
console.log("UNVOR AI per-user encryption, native settings, 3-provider fallback and HUD actions OK");

const grid=fs.readFileSync(path.join(root,"assets/hud/app-grid.css"),"utf8");
const dock=index.match(/<nav class="dock"[\s\S]*?<\/nav>/)?.[0]||"";
assert.match(dock,/data-action="calls"[\s\S]*?data-action="sms"[\s\S]*?data-action="apps"[\s\S]*?data-action="browser"[\s\S]*?data-action="ultron"/);
assert.doesNotMatch(dock,/data-action="settings"/);
assert.match(index,/data-action="settings"[^>]*aria-label="Impostazioni"/);
