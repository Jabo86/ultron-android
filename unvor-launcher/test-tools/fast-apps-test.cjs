assert.match(js,/else if\(a==='aiSettings'\)aiSettings\(\)/);
assert.match(js,/function renderApps\(rows\)/);
assert.match(js,/grid\.className='unvor-app-grid'/);
assert.match(js,/tile\.className='unvor-app-tile'/);
